"""CST-22 geometry harness — design space SHARED by MLP <-> SU2 (Phase D, optimization).

CANONICAL convention = dataset_v3_rans (columns cst_0..cst_21): this is the input
CONTRACT of the MLP. Every shape (baseline OR generated by the optimizer) must go through
`encode` -> the MLP always sees in-distribution input. `decode(cst22)` = THE geometry that
this vector means, sent to gmsh/SU2. The pipeline is self-consistent by construction.

Encoder/decoder replicated identically from:
  - src/utils/cst.py::fit_cst  (encode, same fit as the dataset)
  - src/uq/geometry.py::recon_coords                                     (decode)
Same Bernstein basis (class x^0.5*(1-x)^1, degree 10, NO TE term). N_CST=11 -> 22 params.

The "baseline" of an optimization is NOT the raw .dat but decode(encode(.dat)) = the
CST-representable version. Fair comparison: all methods start from the same x, same
representation power. Native SU2 (Hicks-Henne) remains the out-of-space ceiling.
"""
import numpy as np
from pathlib import Path

from src.utils.cst import fit_cst
from src.uq.geometry import recon_coords

N_CST = 11  # 11 upper + 11 lower = 22, identical to build_dataset_v3


def encode(coords: np.ndarray) -> np.ndarray:
    """Coords (N,2) -> cst22, EXACTLY as build_dataset_v3._fit_cst_from_coords.
    TE term dropped (the dataset never kept it)."""
    r = fit_cst(np.asarray(coords, dtype=float), n_cst=N_CST)
    return np.concatenate([r["A_upper"], r["A_lower"]]).astype(float)  # (22,)


def decode(cst22: np.ndarray, n: int = 160) -> np.ndarray:
    """cst22 -> coords (2n-1, 2) in Selig order (TE_upper -> LE -> TE_lower), ready for gmsh."""
    return recon_coords(np.asarray(cst22, dtype=float), n=n)


def fit_dat(path: str) -> np.ndarray:
    """Loads a Selig .dat (1st line = name) -> cst22."""
    coords = np.loadtxt(path, skiprows=1)
    return encode(coords)


def save_dat(cst22: np.ndarray, path: str, name: str = "airfoil", n: int = 160) -> None:
    """Writes a Selig .dat from cst22 (for meshing / archiving)."""
    xy = decode(cst22, n=n)
    with open(path, "w") as f:
        f.write(f"{name}\n")
        for x, y in xy:
            f.write(f"{x:.6f} {y:.6f}\n")
